test("rejects manifest traversal and duplicate paths", () => {
  const input = fixture();
  const result = createCheckpoint(input);
  const manifest = JSON.parse(readFileSync(result.manifestPath));
  assert.throws(() => verifyCheckpoint(result.checkout, { ...manifest, files: [{ path: "../outside.ts", bytes: 0, sha256: "" }] }), /Invalid relative candidate path/);
  assert.throws(() => verifyCheckpoint(result.checkout, { ...manifest, files: [...manifest.files, manifest.files[0]] }), /Duplicate manifest path/);
});

