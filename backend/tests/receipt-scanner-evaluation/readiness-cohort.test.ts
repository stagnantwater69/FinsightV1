import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";
import { buildReadinessReport, readinessExitCode, verifyDeclaredImages } from "./cohort-readiness";
import { localCorpusEntrySchema, type LocalCorpusEntry } from "./local-corpus-contract";
import { COHORT_TAGS } from "./policy-v1-contract";
import { runReadinessReport } from "./run-readiness-report";

vi.mock("../../src/services/ocr.service", () => { throw new Error("Readiness must not import OCR"); });
vi.mock("../../src/services/visionOcr.service", () => { throw new Error("Readiness must not import a provider"); });

const temporaryDirectories: string[] = [];
function temporaryDirectory() {
  const path = mkdtempSync(join(tmpdir(), "finsight-readiness-contract-"));
  temporaryDirectories.push(path);
  return path;
}
afterEach(() => {
  vi.restoreAllMocks();
  for (const path of temporaryDirectories.splice(0)) {
    if (dirname(resolve(path)) !== resolve(tmpdir()) || !basename(path).startsWith("finsight-readiness-contract-")) {
      throw new Error("Temporary cleanup target is outside the test directory");
    }
    rmSync(path, { recursive: true, force: true });
  }
});

// Generated bytes and declarations below test the intake contract, never real receipt accuracy.
function declaredEntry(overrides: Record<string, unknown> = {}): LocalCorpusEntry {
  return localCorpusEntrySchema.parse({
    id: "private_sample_id",
    file: "test-only.bin",
    kind: "real",
    conditions: "Synthetic declaration for contract verification only",
    provenance: {
      label: "ANONYMIZED_CONSENTED_REAL_DOUBLE_REVIEWED",
      consentRecorded: true, anonymizationReviewed: true, groundTruthReviewerCount: 2,
    },
    developmentCohort: {
      receiptGroupId: "private_receipt_id", vendorTemplateId: "private_template_id",
      sourceSha256: createHash("sha256").update("test bytes").digest("hex"),
      partition: "HOLDOUT", cohortTags: [...COHORT_TAGS], languageTags: ["MIXED"],
      reviewerIds: ["private_reviewer_one", "private_reviewer_two"],
      captureConditions: {
        jurisdiction: "PH", lighting: "LOW_LIGHT", perspective: "SKEWED", pageCount: 2,
        handwriting: "HANDWRITTEN_OR_ANNOTATED", printQuality: "FADED_OR_STRESSED",
      },
    },
    expected: { vendor: "Private receipt name", date: "2026-10-13", amount: 100, items: [] },
    ...overrides,
  });
}

describe("representative receipt readiness", () => {
  it("reports the actual declared corpus as 73 excluded with no measured accuracy", () => {
    const entries = localCorpusEntrySchema.array().parse(JSON.parse(readFileSync(join(__dirname, "../ocr-accuracy/ground-truth.json"), "utf8")));
    const report = buildReadinessReport(entries);
    expect(report.counts).toMatchObject({ totalManifestEntries: 73, eligibleSamples: 0, excludedSamples: 73, uniqueEligibleReceipts: 0 });
    expect(report.counts.exclusionsByReason).toMatchObject({ SYNTHETIC_OR_DERIVED: 28, PUBLIC_SINGLE_REVIEW: 42, UNKNOWN_CONSENT: 3 });
    expect(report.status).toBe("BLOCKED_NO_ELIGIBLE_SAMPLES");
    expect(report.metrics.totalAccuracy).toBeNull();
    expect(report.metrics.failureRate).toBeNull();
    expect(report.coverage.missingCaptureConditions).toHaveLength(5);
    expect(readinessExitCode(report)).toBe(3);
  });

  it("marks complete declared coverage ready to evaluate without claiming accuracy or verified humans", () => {
    const report = buildReadinessReport([declaredEntry()]);
    expect(report.status).toBe("READY_FOR_LOCAL_EVALUATION");
    expect(readinessExitCode(report)).toBe(0);
    expect(report.accuracyStatus).toBe("NOT_MEASURED");
    expect(report.accuracyClaimSupported).toBe(false);
    expect(report.consentAndIndependentReviewVerified).toBe(false);
    for (const secret of ["private_sample_id", "private_receipt_id", "private_template_id", "private_reviewer_one", "Private receipt name", "test-only.bin"]) {
      expect(JSON.stringify(report)).not.toContain(secret);
    }
  });

  it("retains unknown conditions as missing coverage", () => {
    const entry = declaredEntry();
    entry.developmentCohort!.captureConditions = { jurisdiction: "PH", lighting: "UNKNOWN", perspective: "UNKNOWN", pageCount: null, handwriting: "UNKNOWN", printQuality: "UNKNOWN" };
    const report = buildReadinessReport([entry]);
    expect(report.counts.eligibleSamples).toBe(1);
    expect(report.status).toBe("BLOCKED_MISSING_COVERAGE");
    expect(report.coverage.missingCaptureConditions).toHaveLength(5);
    expect(report.coverage.unknownCaptureMetadata).toEqual({ lighting: 1, perspective: 1, pageCount: 1, handwriting: 1, printQuality: 1 });
  });

  it.each(["OTHER", "UNKNOWN"] as const)("does not infer PH receipts from %s jurisdiction", (jurisdiction) => {
    const entry = declaredEntry();
    entry.developmentCohort!.captureConditions!.jurisdiction = jurisdiction;
    const report = buildReadinessReport([entry]);
    expect(report.counts.eligibleSamples).toBe(0);
    expect(report.counts.exclusionsByReason.PH_JURISDICTION_NOT_DECLARED).toBe(1);
  });

  it("excludes calibration and missing condition declarations", () => {
    const calibration = declaredEntry();
    calibration.developmentCohort!.partition = "CALIBRATION";
    expect(buildReadinessReport([calibration]).counts.exclusionsByReason.CALIBRATION_ONLY).toBe(1);
    const missing = declaredEntry();
    delete missing.developmentCohort!.captureConditions;
    expect(buildReadinessReport([missing]).counts.exclusionsByReason.CAPTURE_CONDITIONS_MISSING).toBe(1);
  });

  it.each(["synthetic", "degraded"] as const)("rejects a %s sample claiming a representative cohort", (kind) => {
    const declaration = declaredEntry();
    const candidate = localCorpusEntrySchema.parse({ ...declaration, kind, provenance: undefined });
    expect(() => buildReadinessReport([candidate])).toThrow(/provenance/);
  });

  it("rejects false consent or insufficient independent ground truth", () => {
    const entry = declaredEntry();
    for (const provenance of [
      { ...entry.provenance, consentRecorded: false },
      { ...entry.provenance, groundTruthReviewerCount: 1 },
      { ...entry.provenance, anonymizationReviewed: false },
    ]) expect(() => localCorpusEntrySchema.parse({ ...entry, provenance })).toThrow();
    const sameReviewer = declaredEntry();
    sameReviewer.developmentCohort!.reviewerIds = ["private_reviewer_one", "private_reviewer_one"];
    expect(() => buildReadinessReport([sameReviewer])).toThrow();
  });

  it("rejects duplicate samples and cross-partition receipt leakage", () => {
    const entry = declaredEntry();
    expect(() => buildReadinessReport([entry, entry])).toThrow(/sample ID/);
    const calibration = declaredEntry({ id: "another_private_sample" });
    calibration.developmentCohort!.partition = "CALIBRATION";
    expect(() => buildReadinessReport([entry, calibration])).toThrow();
  });

  it("deduplicates logical receipt counts while retaining capture sample counts", () => {
    const first = declaredEntry();
    const recapture = declaredEntry({ id: "recapture_sample_id" });
    const report = buildReadinessReport([first, recapture]);
    expect(report.counts.eligibleSamples).toBe(2);
    expect(report.counts.uniqueEligibleReceipts).toBe(1);
    expect(report.coverage.captureConditions.LOW_LIGHT).toEqual({ samples: 2, uniqueReceipts: 1, failureRate: null });
  });

  it("rejects missing and changed image bytes, including the other partition", () => {
    const root = temporaryDirectory();
    const entry = declaredEntry();
    entry.developmentCohort!.partition = "CALIBRATION";
    expect(() => verifyDeclaredImages([entry], root)).toThrow(/unavailable/);
    writeFileSync(join(root, entry.file), "changed bytes");
    expect(() => verifyDeclaredImages([entry], root)).toThrow(/changed/);
    writeFileSync(join(root, entry.file), "test bytes");
    expect(() => verifyDeclaredImages([entry], root)).not.toThrow();
  });

  it("rejects identical image bytes assigned to different logical receipts", () => {
    const first = declaredEntry();
    const duplicate = declaredEntry({ id: "another_private_sample" });
    duplicate.developmentCohort!.receiptGroupId = "another_private_receipt";
    expect(() => buildReadinessReport([first, duplicate])).toThrow(/different logical receipts/);
  });

  it("rejects a directory substituted for an image", () => {
    const root = temporaryDirectory();
    const entry = declaredEntry();
    mkdirSync(join(root, entry.file));
    expect(() => verifyDeclaredImages([entry], root)).toThrow(/regular file/);
  });

  it("rejects an image-directory link escaping the declared root", () => {
    const root = temporaryDirectory();
    const outside = temporaryDirectory();
    writeFileSync(join(outside, "outside.bin"), "test bytes");
    symlinkSync(outside, join(root, "linked"), process.platform === "win32" ? "junction" : "dir");
    const entry = declaredEntry({ file: join("linked", "outside.bin") });
    expect(() => verifyDeclaredImages([entry], root)).toThrow(/outside/);
    expect(readFileSync(join(outside, "outside.bin"), "utf8")).toBe("test bytes");
  });

  it("writes zero-eligible blocked evidence without importing an extractor or overwriting output", () => {
    const root = temporaryDirectory();
    const output = join(root, "aggregate.json");
    const stdout = vi.spyOn(process.stdout, "write").mockImplementation(() => true);
    vi.spyOn(process.stderr, "write").mockImplementation(() => true);
    expect(runReadinessReport(["--output", output])).toBe(3);
    const bytes = readFileSync(output, "utf8");
    expect(JSON.parse(bytes).counts.eligibleSamples).toBe(0);
    expect(JSON.parse(bytes).ocrExecuted).toBe(false);
    expect(JSON.parse(bytes).externalProviderCalls).toBe(false);
    expect(stdout).toHaveBeenCalled();
    expect(runReadinessReport(["--output", output])).toBe(2);
    expect(readFileSync(output, "utf8")).toBe(bytes);
  });
});
